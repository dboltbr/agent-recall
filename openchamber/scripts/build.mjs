// Builds the OpenChamber extension in place: one classic IIFE per page entry (`<entry>/main.js`,
// the sandboxed iframes cannot load ESM) and the host service as one ESM file (`service/main.js`).
// The folder is then installable from Settings → Extensions as is.
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const banner = "// @agent-recall/openchamber-release: generated by openchamber/scripts/build.mjs. Copyright DBolt. All rights reserved.";

const pages = ["panel", "page", "status", "background"];

/** `zod` resolves to `zod-slim.ts` (see there) in every bundle. */
const slimZod = {
  name: "slim-zod",
  setup(build) {
    const slim = join(root, "scripts", "zod-slim.ts");
    build.onResolve({ filter: /^zod$/ }, (args) => (args.importer === slim ? undefined : { path: slim }));
  },
};

await Promise.all([
  ...pages.map((entry) =>
    build({
      entryPoints: [join(root, "src", entry, "main.ts")],
      outfile: join(root, entry, "main.js"),
      bundle: true,
      platform: "browser",
      format: "iife",
      target: "es2022",
      minify: true,
      legalComments: "none",
      banner: { js: banner },
      plugins: [slimZod],
    }),
  ),
  build({
    entryPoints: [join(root, "src", "service", "main.ts")],
    outfile: join(root, "service", "main.js"),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    legalComments: "none",
    banner: { js: banner },
    plugins: [slimZod],
  }),
]);
console.log(`openchamber: ${pages.map((entry) => `${entry}/main.js`).join(", ")}, service/main.js`);
