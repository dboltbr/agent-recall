// Bundles opencode/index.ts (with core/) into dist/agent-recall.js, the single file OpenCode loads
// from the git install (`main`/`exports` in package.json). AGENT_RECALL_BUILD_SHA is the source commit it was built
// from: the commit that adds the bundle cannot contain its own SHA.
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

await build({
  entryPoints: [join(root, "opencode", "index.ts")],
  outfile: join(root, "dist", "agent-recall.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "none",
  banner: { js: "// agent-recall: generated by scripts/build-opencode.mjs. Copyright DBolt. All rights reserved." },
  define: { AGENT_RECALL_BUILD_SHA: JSON.stringify(sha) },
});
console.log(`dist/agent-recall.js built from ${sha.slice(0, 12)}`);
