// Bundles claude/index.ts (with core/) into claude/dist/watch.mjs (.mjs: claude/ has no package.json
// with "type": "module", and Node without syntax detection reads .js as CommonJS), the script the Claude Code plugin's
// hooks run (claude/bin/watch.sh). Claude Code installs the plugin by copying the claude/ directory
// from git, with no npm install, so the bundle lives inside it and goes in the commit.
// AGENT_RECALL_BUILD_SHA is the source commit it was built from.
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

await build({
  entryPoints: [join(root, "claude", "index.ts")],
  outfile: join(root, "claude", "dist", "watch.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "none",
  banner: { js: "// agent-recall: generated by scripts/build-claude.mjs. Copyright DBolt. All rights reserved." },
  define: { AGENT_RECALL_BUILD_SHA: JSON.stringify(sha) },
});
console.log(`claude/dist/watch.mjs built from ${sha.slice(0, 12)}`);
